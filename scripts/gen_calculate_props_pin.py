"""Generate core/mppwrite/calculate_props_pin.inc: the measured control's 114/Props, pinned
(W35c-0.3, R35bG0-2).

Calculate Project (core/mppwrite/calculate.cpp) refuses a file whose 114/Props differs from
the measured control's, because the project's calculation options (multiple critical paths,
the critical-slack limit, minutes per day and per week, schedule from) live there and no pair
varies them.  The control is tests/data/wave35-calculate-unlinked-control.mpp, a file Project
saved (never opened in place: this script only reads it).

What is pinned: the 16-byte header words at +8 and +12; for each of the framed records its id,
kind, length and the FNV-1a 64 hash of its payload, in stream order; and the opaque tail's
length and FNV-1a 64 hash with the value word of the one scalar the save itself rewrites
(tag 0x01000100, the Task Var2Data size, spelled 0x00010001 in the decode notes) zeroed.

The writer exempts, by id, the records a save or a measured relation moves: 0x02400003 (project
finish) and 0x02400024 (the pending flag), which the save writes; 0x02400002 (the project
start), which 0.2 relates to the leaf Start; and the two 16-byte GUID records whose payload the
null save changes (control vs null save: 0x02400029 and 0x024013c2).  Their id, kind and length
stay pinned.

Usage: python scripts/gen_calculate_props_pin.py [--check]
  without --check, rewrites the .inc; with --check, exits 1 when the .inc is out of date.
"""
import struct
import sys
from pathlib import Path

import olefile

ROOT = Path(__file__).resolve().parent.parent
CONTROL = ROOT / "tests" / "data" / "wave35-calculate-unlinked-control.mpp"
NULL_SAVE = ROOT / "tests" / "data" / "wave35-calculate-unlinked-control-null.mpp"
OUT = ROOT / "core" / "mppwrite" / "calculate_props_pin.inc"
TAIL_KEY_TAG = 0x01000100  # big-endian spelling of the 16-byte scalar's tag


def props_of(path):
    ole = olefile.OleFileIO(str(path))
    try:
        for entry in ole.listdir():
            if entry[-1] == "Props" and entry[-2].strip() == "114":
                return ole.openstream(entry).read()
    finally:
        ole.close()
    raise SystemExit("no 114/Props in " + str(path))


def fnv64(data):
    value = 0xCBF29CE484222325
    for byte in data:
        value ^= byte
        value = (value * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return value


def framed(raw):
    out = []
    at = 16
    while at + 12 <= len(raw):
        length, ident, kind = struct.unpack_from("<III", raw, at)
        if (ident & 0x00FF0000) != 0x00400000:
            break
        out.append((ident, kind, length, raw[at + 12:at + 12 + length]))
        at += 12 + length
    return out, at


def tail_key_value_offset(tail):
    found = []
    for at in range(0, len(tail) - 15, 16):
        length_a, tag, length_b = struct.unpack_from(">III", tail, at)
        if struct.unpack_from("<I", tail, at)[0] == 4 and \
                struct.unpack_from("<I", tail, at + 8)[0] == 4 and tag == TAIL_KEY_TAG:
            found.append(at + 12)
    if len(found) != 1:
        raise SystemExit("the tail holds %d scalar records for tag 0x%08x" % (len(found), TAIL_KEY_TAG))
    return found[0]


def render():
    raw = props_of(CONTROL)
    records, tail_start = framed(raw)
    tail = bytearray(raw[tail_start:])
    at = tail_key_value_offset(bytes(tail))
    tail[at:at + 4] = b"\0\0\0\0"
    lines = [
        "/* GENERATED by scripts/gen_calculate_props_pin.py from the measured control",
        " * (tests/data/wave35-calculate-unlinked-control.mpp).  Do not edit by hand:",
        " * `python scripts/gen_calculate_props_pin.py --check` fails when this is stale. */",
        "",
        "constexpr std::uint32_t kPropsPinHeaderWord8 = 0x%08Xu;" % struct.unpack_from("<I", raw, 8)[0],
        "constexpr std::uint32_t kPropsPinHeaderWord12 = 0x%08Xu;" % struct.unpack_from("<I", raw, 12)[0],
        "constexpr std::size_t kPropsPinTailBytes = %d;" % len(tail),
        "constexpr std::uint64_t kPropsPinTailHash = 0x%016XULL;" % fnv64(tail),
        "constexpr PropsPinRecord kPropsPin[] = {",
    ]
    for ident, kind, length, payload in records:
        lines.append("    {0x%08Xu, %d, %d, 0x%016XULL}," % (ident, kind, length, fnv64(payload)))
    lines.append("};")
    return "\n".join(lines) + "\n", records, raw


def main():
    text, records, raw = render()
    # the exempt GUID records are the ones the null save changes
    null_records, _ = framed(props_of(NULL_SAVE))
    noisy = sorted(r[0] for r, n in zip(records, null_records) if r[3] != n[3])
    print("records:", len(records), "tail bytes:", len(raw), "noise ids:", ["0x%08x" % i for i in noisy])
    expected = [0x02400029, 0x024013C2]
    if noisy != expected:
        raise SystemExit("the null save's noisy records are not the two the writer exempts: %r" % noisy)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("STALE:", OUT)
            return 1
        print("up to date:", OUT)
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
