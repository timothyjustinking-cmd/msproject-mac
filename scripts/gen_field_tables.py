#!/usr/bin/env python3
"""Generate the MS Project field descriptor table from the analysis TSVs.

The authoritative field inventory is ``analysis/field_metadata_all.tsv``:
3,207 rows, 11 columns.  That file does *not* contain the storage columns
(storage class/name, linked field, secondary index, sub type), even though the
stream brief listed them.  Those columns are in
``analysis/field_definitive_map.tsv``, which has the same 3,207 rows in the same
order.  This generator joins the two files 1:1 by
``(record_type, field_id_hex)`` and refuses to emit if the join or any of the
shared columns disagree.

Both TSVs use CRLF line endings.  Read them with ``newline=''`` so the csv
module strips the CR rather than leaving it in the final column.

Usage:
    python scripts/gen_field_tables.py
    python scripts/gen_field_tables.py --check
    python scripts/gen_field_tables.py --metadata PATH --definitive PATH --out-dir PATH

``--check`` regenerates into a temporary directory and diffs against the
committed files.  It exits non-zero on any source validation failure or on any
content difference.  Line endings are normalised to LF before the comparison:
a Windows checkout with ``core.autocrlf=true`` (the GitHub Windows runner
default) writes the committed LF files as CRLF on disk, which is a property of
the checkout, not staleness.  It is wired into CTest by CMakeLists.txt.
"""

from __future__ import annotations

import argparse
import csv
import difflib
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Snapshot invariants.  These numbers come from the 2026-10-22 analysis and are
# asserted on every run; a change must be a deliberate, reviewed edit here.
# ---------------------------------------------------------------------------

TOTAL_FIELDS = 3207

# The order is the order of field_metadata_all.tsv and is also the order of the
# generated table.  It defines the precedence of unscoped name lookup.
RECORD_ORDER = [
    "Task",
    "Resource",
    "Assignment",
    "Links",
    "Calendar",
    "Project",
    "OutlineCode",
    "Task34",
]

EXPECTED_COUNTS = {
    "Task": 1444,
    "Resource": 883,
    "Assignment": 777,
    "Links": 30,
    "Calendar": 14,
    "Project": 9,
    "OutlineCode": 16,
    "Task34": 34,
}

# First and last field id of each record type.  The ids are contiguous in the
# TSV; the generator verifies that rather than trusting these values alone.
EXPECTED_ID_RANGES = {
    "Task": (0x0B400000, 0x0B4005A3),
    "Resource": (0x0C400000, 0x0C400372),
    "Assignment": (0x0F400000, 0x0F400308),
    "Links": (0x0E400000, 0x0E40001D),
    "Calendar": (0x3C400000, 0x3C40000D),
    "Project": (0x07400000, 0x07400008),
    "OutlineCode": (0x3E400000, 0x3E40000F),
    "Task34": (0x16400000, 0x16400021),
}

METADATA_COLUMNS = [
    "record_type",
    "index",
    "field_id_hex",
    "field_id_dec",
    "property_name",
    "vtable_type",
    "type_code",
    "type_name",
    "record_offset",
    "size",
    "flags_hex",
]

DEFINITIVE_COLUMNS = [
    "record_type",
    "field_id_hex",
    "field_id_dec",
    "com_property_name",
    "engine_type_code",
    "engine_type_name",
    "slot_index",
    "field_size",
    "flags_hex",
    "storage_class",
    "storage_name",
    "class_slot",
    "byte_offset_hex",
    "byte_offset_dec",
    "linked_field_hex",
    "secondary_idx",
    "sub_type",
    "vtable_class",
]

GENERATED_BANNER = """\
// Generated by scripts/gen_field_tables.py -- DO NOT EDIT BY HAND.
//
// Sources, joined 1:1 by (record_type, field_id):
//   analysis/field_metadata_all.tsv    (3,207 rows, authoritative)
//   analysis/field_definitive_map.tsv  (3,207 rows, storage detail)
//
// Regenerate: python scripts/gen_field_tables.py
// Check:      python scripts/gen_field_tables.py --check
"""


class GeneratorError(RuntimeError):
    pass


def fail(message: str) -> None:
    raise GeneratorError(message)


def read_tsv(path: Path, required: list[str]) -> tuple[list[str], list[tuple[int, dict[str, str]]]]:
    if not path.is_file():
        fail(f"missing TSV: {path}")
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        if reader.fieldnames is None:
            fail(f"{path}: empty file")
        headers = list(reader.fieldnames)
        missing = [name for name in required if name not in headers]
        if missing:
            fail(f"{path}: missing required column(s): {', '.join(missing)}")
        rows: list[tuple[int, dict[str, str]]] = []
        for line_number, row in enumerate(reader, start=2):
            if None in row:
                fail(f"{path}:{line_number}: too many columns")
            if any(row.get(name) is None for name in required):
                fail(f"{path}:{line_number}: too few columns")
            rows.append((line_number, row))
    return headers, rows


def parse_int(value: str, what: str, path: Path, line: int) -> int:
    text = value.strip()
    if text == "":
        fail(f"{path}:{line}: {what} is empty")
    try:
        return int(text, 10)
    except ValueError:
        fail(f"{path}:{line}: {what} is not a decimal integer: {value!r}")


def parse_hex(value: str, what: str, path: Path, line: int) -> int:
    text = value.strip()
    if text.lower().startswith("0x"):
        text = text[2:]
    if text == "":
        fail(f"{path}:{line}: {what} is empty")
    try:
        return int(text, 16)
    except ValueError:
        fail(f"{path}:{line}: {what} is not hexadecimal: {value!r}")


def parse_optional_int(value: str, what: str, path: Path, line: int, default: int) -> int:
    text = value.strip()
    if text == "":
        return default
    try:
        return int(text, 10)
    except ValueError:
        fail(f"{path}:{line}: {what} is not a decimal integer: {value!r}")


def parse_optional_hex(value: str, what: str, path: Path, line: int, default: int) -> int:
    text = value.strip()
    if text == "":
        return default
    return parse_hex(text, what, path, line)


def check_ascii(value: str, what: str, path: Path, line: int) -> None:
    for ch in value:
        code = ord(ch)
        if code < 0x20 or code > 0x7E:
            fail(f"{path}:{line}: {what} contains non-printable/non-ASCII U+{code:04X}: {value!r}")


def c_string(value: str) -> str:
    """Return a C++ string literal.  The generator has already checked ASCII."""
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def uint32_literal(value: int) -> str:
    return f"0x{value:08x}u"


def int_literal(value: int) -> str:
    return str(value)


def render(metadata_path: Path, definitive_path: Path) -> tuple[str, str, dict[str, object]]:
    _, metadata_rows = read_tsv(metadata_path, METADATA_COLUMNS)
    _, definitive_rows = read_tsv(definitive_path, DEFINITIVE_COLUMNS)

    if len(metadata_rows) != TOTAL_FIELDS:
        fail(
            f"{metadata_path}: expected {TOTAL_FIELDS} data rows, "
            f"found {len(metadata_rows)}"
        )
    if len(definitive_rows) != TOTAL_FIELDS:
        fail(
            f"{definitive_path}: expected {TOTAL_FIELDS} data rows, "
            f"found {len(definitive_rows)}"
        )

    # ------------------------------------------------------------------
    # Definitive map: index by (record_type, field id).
    # ------------------------------------------------------------------
    definitive: dict[tuple[str, int], tuple[int, dict[str, str]]] = {}
    for line, row in definitive_rows:
        record = row["record_type"]
        if record not in EXPECTED_COUNTS:
            fail(f"{definitive_path}:{line}: unknown record_type {record!r}")
        field_id = parse_hex(row["field_id_hex"], "field_id_hex", definitive_path, line)
        field_id_dec = parse_int(row["field_id_dec"], "field_id_dec", definitive_path, line)
        if field_id != field_id_dec:
            fail(
                f"{definitive_path}:{line}: field_id_hex {field_id:#x} != "
                f"field_id_dec {field_id_dec}"
            )
        key = (record, field_id)
        if key in definitive:
            fail(f"{definitive_path}:{line}: duplicate field id {record} {field_id:#x}")
        if row["vtable_class"] != "PropInfoData":
            fail(
                f"{definitive_path}:{line}: unexpected vtable_class "
                f"{row['vtable_class']!r} (the generated table stores only "
                "PropInfoData)"
            )
        definitive[key] = (line, row)

    # ------------------------------------------------------------------
    # Authoritative metadata rows, in file order.
    # ------------------------------------------------------------------
    fields: list[dict[str, object]] = []
    seen_ids: set[int] = set()
    record_run: list[str] = []
    counts: dict[str, int] = {name: 0 for name in RECORD_ORDER}
    next_index: dict[str, int] = {name: 0 for name in RECORD_ORDER}
    first_id: dict[str, int] = {}
    last_id: dict[str, int] = {}
    name_count = 0
    storage_count = 0

    for line, row in metadata_rows:
        record = row["record_type"]
        if record not in EXPECTED_COUNTS:
            fail(f"{metadata_path}:{line}: unknown record_type {record!r}")
        if not record_run or record_run[-1] != record:
            if record in record_run:
                fail(f"{metadata_path}:{line}: record_type {record!r} is not contiguous")
            record_run.append(record)

        index = parse_int(row["index"], "index", metadata_path, line)
        if index != next_index[record]:
            fail(
                f"{metadata_path}:{line}: {record} index {index} != expected "
                f"{next_index[record]} (per-record indexes must be sequential)"
            )
        next_index[record] = index + 1

        field_id = parse_hex(row["field_id_hex"], "field_id_hex", metadata_path, line)
        field_id_dec = parse_int(row["field_id_dec"], "field_id_dec", metadata_path, line)
        if field_id != field_id_dec:
            fail(
                f"{metadata_path}:{line}: field_id_hex {field_id:#x} != "
                f"field_id_dec {field_id_dec}"
            )
        if field_id in seen_ids:
            fail(f"{metadata_path}:{line}: duplicate field id {field_id:#x}")
        if field_id > 0xFFFFFFFF:
            fail(f"{metadata_path}:{line}: field id {field_id:#x} does not fit uint32")
        seen_ids.add(field_id)

        if row["vtable_type"] != "PropInfoData":
            fail(
                f"{metadata_path}:{line}: unexpected vtable_type "
                f"{row['vtable_type']!r}"
            )

        engine_type_code = parse_int(row["type_code"], "type_code", metadata_path, line)
        record_offset = parse_int(row["record_offset"], "record_offset", metadata_path, line)
        size = parse_int(row["size"], "size", metadata_path, line)
        flags = parse_hex(row["flags_hex"], "flags_hex", metadata_path, line)

        name = row["property_name"]
        type_name = row["type_name"]
        check_ascii(name, "property_name", metadata_path, line)
        check_ascii(type_name, "type_name", metadata_path, line)
        if name:
            name_count += 1

        key = (record, field_id)
        if key not in definitive:
            fail(f"{definitive_path}: no row for {record} {field_id:#x}")
        def_line, def_row = definitive[key]

        # Shared columns must agree exactly.  This is the core of the
        # self-validation: the storage detail is not allowed to describe a
        # different field than the authoritative table.
        checks = [
            ("record_type", record, def_row["record_type"], "string"),
            ("field_id_dec", field_id_dec, parse_int(
                def_row["field_id_dec"], "field_id_dec", definitive_path, def_line), "int"),
            ("property_name", name, def_row["com_property_name"], "string"),
            ("type_code", engine_type_code, parse_int(
                def_row["engine_type_code"], "engine_type_code", definitive_path, def_line), "int"),
            ("record_offset/slot_index", record_offset, parse_int(
                def_row["slot_index"], "slot_index", definitive_path, def_line), "int"),
            ("size/field_size", size, parse_int(
                def_row["field_size"], "field_size", definitive_path, def_line), "int"),
            ("flags_hex", flags, parse_hex(
                def_row["flags_hex"], "flags_hex", definitive_path, def_line), "int"),
        ]
        for label, left, right, kind in checks:
            if left != right:
                fail(
                    f"{definitive_path}:{def_line}: {label} disagrees with "
                    f"{metadata_path}:{line}: metadata={left!r} definitive={right!r}"
                )

        engine_type_name = def_row["engine_type_name"]
        storage_name = def_row["storage_name"]
        check_ascii(engine_type_name, "engine_type_name", definitive_path, def_line)
        check_ascii(storage_name, "storage_name", definitive_path, def_line)
        if engine_type_name == "":
            fail(f"{definitive_path}:{def_line}: engine_type_name is empty")

        storage_class = parse_optional_int(
            def_row["storage_class"], "storage_class", definitive_path, def_line, -1
        )
        if storage_class != -1:
            storage_count += 1
        class_slot = parse_optional_int(
            def_row["class_slot"], "class_slot", definitive_path, def_line, -1
        )
        linked_field = parse_optional_hex(
            def_row["linked_field_hex"], "linked_field_hex", definitive_path, def_line, 0
        )
        secondary_index = parse_optional_int(
            def_row["secondary_idx"], "secondary_idx", definitive_path, def_line, -1
        )
        sub_type = parse_optional_int(
            def_row["sub_type"], "sub_type", definitive_path, def_line, -1
        )

        # byte_offset_hex/byte_offset_dec are not part of the public struct, but
        # they must still agree with each other when present.
        byte_hex = def_row["byte_offset_hex"].strip()
        byte_dec = def_row["byte_offset_dec"].strip()
        if bool(byte_hex) != bool(byte_dec):
            fail(
                f"{definitive_path}:{def_line}: byte_offset_hex/byte_offset_dec "
                "are only half populated"
            )
        if byte_hex:
            if parse_hex(byte_hex, "byte_offset_hex", definitive_path, def_line) != parse_int(
                byte_dec, "byte_offset_dec", definitive_path, def_line
            ):
                fail(
                    f"{definitive_path}:{def_line}: byte_offset_hex and "
                    "byte_offset_dec disagree"
                )

        if storage_class != -1 and not storage_name:
            fail(
                f"{definitive_path}:{def_line}: storage_class {storage_class} "
                "has no storage_name"
            )
        if storage_class == -1 and storage_name:
            fail(
                f"{definitive_path}:{def_line}: storage_name {storage_name!r} "
                "has no storage_class"
            )

        counts[record] += 1
        if record not in first_id:
            first_id[record] = field_id
        last_id[record] = field_id

        fields.append(
            {
                "record": record,
                "index": index,
                "field_id": field_id,
                "name": name,
                "type_code": engine_type_code,
                "type_name": type_name,
                "engine_type_name": engine_type_name,
                "storage_class": storage_class,
                "storage_name": storage_name,
                "slot_index": record_offset,
                "field_size": size,
                "flags": flags,
                "linked_field": linked_field,
                "class_slot": class_slot,
                "secondary_index": secondary_index,
                "sub_type": sub_type,
            }
        )

    # ------------------------------------------------------------------
    # Cross-row invariants.
    # ------------------------------------------------------------------
    if record_run != RECORD_ORDER:
        fail(
            "record type order changed: expected "
            f"{RECORD_ORDER}, found {record_run}"
        )
    for record in RECORD_ORDER:
        if counts[record] != EXPECTED_COUNTS[record]:
            fail(
                f"{record}: expected {EXPECTED_COUNTS[record]} fields, "
                f"found {counts[record]}"
            )
        expected_first, expected_last = EXPECTED_ID_RANGES[record]
        if first_id[record] != expected_first or last_id[record] != expected_last:
            fail(
                f"{record}: id range {first_id[record]:#x}..{last_id[record]:#x}, "
                f"expected {expected_first:#x}..{expected_last:#x}"
            )
        expected_span = expected_last - expected_first + 1
        if expected_span != counts[record]:
            fail(
                f"{record}: id range spans {expected_span} ids but has "
                f"{counts[record]} fields"
            )

    # The Task range is the one the brief calls out explicitly: every id from
    # 0x0b400000 through 0x0b4005a3 must be present with no gaps.
    task_ids = {f["field_id"] for f in fields if f["record"] == "Task"}
    expected_task_ids = set(range(EXPECTED_ID_RANGES["Task"][0], EXPECTED_ID_RANGES["Task"][1] + 1))
    missing_task = sorted(expected_task_ids - task_ids)
    if missing_task:
        fail(
            "Task field ids missing from the table: "
            + ", ".join(f"{value:#x}" for value in missing_task[:20])
        )

    if len(definitive) != len(fields):
        fail(f"{definitive_path}: {len(definitive)} unique rows but {len(fields)} metadata rows")

    # linked_field must point at a real descriptor when set.
    missing_links = sorted(
        {f["linked_field"] for f in fields if f["linked_field"] and f["linked_field"] not in seen_ids}
    )
    if missing_links:
        fail(
            "linked_field values that are not field ids in this table: "
            + ", ".join(f"{value:#x}" for value in missing_links[:20])
        )

    # ------------------------------------------------------------------
    # Emit.
    # ------------------------------------------------------------------
    header = build_header(counts, first_id, last_id)
    source = build_source(fields)

    summary = {
        "fields": len(fields),
        "counts": counts,
        "name_count": name_count,
        "storage_count": storage_count,
        "first_id": first_id,
        "last_id": last_id,
    }
    return header, source, summary


def generate(metadata_path: Path, definitive_path: Path, out_dir: Path) -> dict[str, object]:
    header, source, summary = render(metadata_path, definitive_path)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "field_table.gen.h").write_bytes(header.encode("utf-8"))
    (out_dir / "field_table.gen.cpp").write_bytes(source.encode("utf-8"))
    summary["out_dir"] = out_dir
    return summary


def build_header(
    counts: dict[str, int], first_id: dict[str, int], last_id: dict[str, int]
) -> str:
    lines: list[str] = []
    lines.append(GENERATED_BANNER)
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append('#include "core_c.h"')
    lines.append("")
    lines.append("namespace core::model::generated {")
    lines.append("")
    lines.append(f"inline constexpr std::size_t kFieldCount = {TOTAL_FIELDS};")
    lines.append("")
    symbol_names = {
        "Task": "Task",
        "Resource": "Resource",
        "Assignment": "Assignment",
        "Links": "Links",
        "Calendar": "Calendar",
        "Project": "Project",
        "OutlineCode": "OutlineCode",
        "Task34": "Task34",
    }
    for record in RECORD_ORDER:
        symbol = symbol_names[record]
        lines.append(
            f"inline constexpr std::size_t k{symbol}FieldCount = {counts[record]};"
        )
    lines.append("")
    for record in RECORD_ORDER:
        symbol = symbol_names[record]
        lines.append(
            f"inline constexpr std::uint32_t k{symbol}FieldIdFirst = "
            f"{uint32_literal(first_id[record])};"
        )
        lines.append(
            f"inline constexpr std::uint32_t k{symbol}FieldIdLast = "
            f"{uint32_literal(last_id[record])};"
        )
    lines.append("")
    lines.append("// Immutable, statically allocated descriptor table.  See core_c.h")
    lines.append("// for the lifetime and ownership contract.")
    lines.append("extern const core_field_info kFields[kFieldCount];")
    lines.append("")
    lines.append("}  // namespace core::model::generated")
    lines.append("")
    return "\n".join(lines)


def build_source(fields: list[dict[str, object]]) -> str:
    lines: list[str] = []
    lines.append(GENERATED_BANNER)
    lines.append('#include "field_table.gen.h"')
    lines.append("")
    lines.append("namespace core::model::generated {")
    lines.append("namespace {")
    lines.append("")
    lines.append("// One row per source row, so the generated diff is reviewable.")
    lines.append("#define CORE_FIELD_ROW(\\")
    lines.append("    id, rec, cache, code, sclass, slot, size, flags, linked, \\")
    lines.append("    class_slot, secondary, subtype, name, engine_type, legacy_type, storage_name) \\")
    lines.append("  { \\")
    lines.append("    id, rec, cache, code, sclass, slot, size, flags, linked, \\")
    lines.append("    class_slot, secondary, subtype, name, engine_type, legacy_type, \\")
    lines.append("    storage_name \\")
    lines.append("  }")
    lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("const core_field_info kFields[kFieldCount] = {")
    record_enum = {
        "Task": "CORE_RECORD_TASK",
        "Resource": "CORE_RECORD_RESOURCE",
        "Assignment": "CORE_RECORD_ASSIGNMENT",
        "Links": "CORE_RECORD_LINKS",
        "Calendar": "CORE_RECORD_CALENDAR",
        "Project": "CORE_RECORD_PROJECT",
        "OutlineCode": "CORE_RECORD_OUTLINE_CODE",
        "Task34": "CORE_RECORD_TASK34",
    }
    for field in fields:
        record = str(field["record"])
        lines.append(
            "  CORE_FIELD_ROW("
            f"{uint32_literal(int(field['field_id']))}, "
            f"{record_enum[record]}, "
            f"{int_literal(int(field['index']))}, "
            f"{int_literal(int(field['type_code']))}, "
            f"{int_literal(int(field['storage_class']))}, "
            f"{int_literal(int(field['slot_index']))}, "
            f"{int_literal(int(field['field_size']))}, "
            f"{uint32_literal(int(field['flags']))}, "
            f"{uint32_literal(int(field['linked_field']))}, "
            f"{int_literal(int(field['class_slot']))}, "
            f"{int_literal(int(field['secondary_index']))}, "
            f"{int_literal(int(field['sub_type']))}, "
            f"{c_string(str(field['name']))}, "
            f"{c_string(str(field['engine_type_name']))}, "
            f"{c_string(str(field['type_name']))}, "
            f"{c_string(str(field['storage_name']))}"
            "),"
        )
    lines.append("};")
    lines.append("")
    lines.append("#undef CORE_FIELD_ROW")
    lines.append("")
    lines.append(
        "static_assert(sizeof(kFields) / sizeof(kFields[0]) == kFieldCount, "
        '"generated field count mismatch");'
    )
    lines.append("")
    lines.append("}  // namespace core::model::generated")
    lines.append("")
    return "\n".join(lines)


def diff_summary(expected_name: str, expected_text: str, actual_text: str) -> str:
    expected_lines = expected_text.splitlines(keepends=True)
    actual_lines = actual_text.splitlines(keepends=True)
    diff = list(
        difflib.unified_diff(
            expected_lines,
            actual_lines,
            fromfile=expected_name,
            tofile="regenerated",
            n=3,
        )
    )
    if not diff:
        return ""
    if len(diff) > 240:
        diff = diff[:240] + ["... diff truncated ...\n"]
    return "".join(diff)


def check(metadata_path: Path, definitive_path: Path, out_dir: Path) -> int:
    header, source, summary = render(metadata_path, definitive_path)
    expected = {
        "field_table.gen.h": header.encode("utf-8"),
        "field_table.gen.cpp": source.encode("utf-8"),
    }
    failures = 0
    for name, generated in expected.items():
        committed = out_dir / name
        if not committed.is_file():
            print(f"FAIL: {committed} does not exist", file=sys.stderr)
            failures += 1
            continue
        actual = committed.read_bytes()
        # The committed files are LF.  A Windows checkout with
        # core.autocrlf=true (the GitHub Windows runner default) turns them into
        # CRLF on disk; that is an environment difference, not stale content, so
        # compare the content with the line endings normalised.
        actual = actual.replace(b"\r\n", b"\n")
        if actual != generated:
            print(f"FAIL: {committed} is stale; run the generator", file=sys.stderr)
            print(
                diff_summary(
                    committed.name,
                    actual.decode("utf-8", errors="replace"),
                    generated.decode("utf-8"),
                ),
                file=sys.stderr,
            )
            failures += 1
    if failures:
        return 1
    print(
        "OK: generated table matches the TSVs: "
        f"{summary['fields']} fields, "
        f"{summary['name_count']} named, "
        f"{summary['storage_count']} with storage detail"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    root = Path(__file__).resolve().parent.parent
    parser.add_argument(
        "--metadata",
        type=Path,
        default=root / "analysis" / "field_metadata_all.tsv",
        help="authoritative 3,207-row field TSV",
    )
    parser.add_argument(
        "--definitive",
        type=Path,
        default=root / "analysis" / "field_definitive_map.tsv",
        help="3,207-row storage-detail TSV",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=root / "core" / "model",
        help="directory for field_table.gen.h/.cpp",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate to a temp dir and fail if the committed files differ",
    )
    args = parser.parse_args(argv)

    try:
        if args.check:
            return check(args.metadata, args.definitive, args.out_dir)
        summary = generate(args.metadata, args.definitive, args.out_dir)
    except GeneratorError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    print(
        "wrote {}/field_table.gen.h and .cpp: "
        "{} fields, {} named, {} with storage detail".format(
            summary["out_dir"],
            summary["fields"],
            summary["name_count"],
            summary["storage_count"],
        )
    )
    for record in RECORD_ORDER:
        print(
            "  {:<12} {:>4} fields  ids {:#010x}..{:#010x}".format(
                record,
                summary["counts"][record],
                summary["first_id"][record],
                summary["last_id"][record],
            )
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
