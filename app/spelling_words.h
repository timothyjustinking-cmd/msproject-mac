// app/spelling_words.h -- the spelling checker's own word list (W30-3.3).
//
// The wave-30 brief forbids dictionary data from Microsoft Project, and this
// port has no portable OS word list (macOS has one, Windows does not).  This
// list is the port's OWN: common English plus the vocabulary a project plan
// uses (schedule, milestone, baseline, stakeholder, ...).  It is deliberately
// modest and the Spelling dialog says so; the check reports words it does not
// know and never suggests or applies a correction, so a word outside the list
// is a prompt for the reader, not a claim that it is misspelt.
//
// The list is lower case ASCII, one word per line, sorted, with no duplicates;
// app/spelling_tests.cpp asserts those four properties so a careless addition
// cannot rot it.  spelling.cpp applies the conservative suffix rules documented
// in spelling.h on top of this list.
//
// PROVENANCE: authored for this port from general English and project
// management vocabulary; no external dictionary file was copied.
