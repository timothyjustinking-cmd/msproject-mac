    t.equal(u32_at(fixed, row + 4), 1, "assignment add: row task uid");
    t.equal(u32_at(fixed, row + 8), 2, "assignment add: row resource uid");
    t.check(f64_at(fixed, row + 12) == 10000.0,
            "assignment add: units 100 % (x100)");
    t.check(f64_at(fixed, row + 20) == 2400000.0,
            "assignment add: work minutes x1000 (2400 min)");
    t.check(f64_at(fixed, row + 28) == 0.0,
            "assignment add: the unmapped +28 f64 is 0");
    t.check(f64_at(fixed, row + 36) == 2400000.0,
            "assignment add: the +36 work copy equals +20");
    t.check(f64_at(fixed, row + 44) == 2400000.0,
            "assignment add: the +44 work copy equals +20");
    t.equal(u32_at(fixed, row + 52), 0x3BF11E78u,
            "assignment add: start is task A's effective +104");
    t.equal(u32_at(fixed, row + 56), 0x3BF61C20u,
            "assignment add: finish is task A's effective +108");
    t.equal(u32_at(fixed, row + 60), u32_at(fixed, row + 52),
            "assignment add: resume defaults to start");
    t.equal(u32_at(fixed, row + 92), 7,
            "assignment add: the measured +92 constant is 7");
    t.equal(u32_at(fixed, row + 104), u32_at(fixed, row + 52),
            "assignment add: the +104 start copy equals +52");

    std::vector<std::uint8_t> const meta = doc.read_stream(kAsnMeta);
    std::size_t const entry = 16 + 3 * 34;
    t.equal(meta[entry], 0, "assignment add: FixedMeta entry state 0 (live)");
    t.equal(u16_at(meta, entry + 2), 4,
            "assignment add: FixedMeta entry field count 4");
    t.equal(u32_at(meta, entry + 4), 330,
            "assignment add: FixedMeta entry names the new row");
    t.equal(u32_at(meta, 4), 4,
            "assignment add: FixedMeta header +4 keeps its 0x04 value");

    std::vector<std::uint8_t> const fixed2 = doc.read_stream(kAsnFixed2);
    std::vector<std::uint8_t> const task_fixed2 = doc.read_stream(kTaskFixed2);
    std::vector<std::uint8_t> const rsc_fixed2 = doc.read_stream(kRscFixed2);
    bool const task_identity = std::equal(
        task_fixed2.begin() + static_cast<std::ptrdiff_t>((1 + 3) * 64),
        task_fixed2.begin() + static_cast<std::ptrdiff_t>((1 + 3) * 64 + 16),
        fixed2.begin() + static_cast<std::ptrdiff_t>(3 * 48 + 16));
    t.check(task_identity,
            "assignment add: Fixed2Data +16 is task A's Task/Fixed2Data identity");
    bool const resource_identity = std::equal(
        rsc_fixed2.begin() + static_cast<std::ptrdiff_t>((2 + 3) * 40),
        rsc_fixed2.begin() + static_cast<std::ptrdiff_t>((2 + 3) * 40 + 16),
        fixed2.begin() + static_cast<std::ptrdiff_t>(3 * 48 + 32));
