std::vector<std::uint32_t> var_keys_for(mppwrite::CfbDocument const& doc,
                                        std::string const& var_meta_path,
                                        std::uint32_t uid) {
    std::vector<mppwrite::VarEntry> const entries =
        mppwrite::read_var_entries(doc.read_stream(var_meta_path));
    std::vector<std::uint32_t> keys;
    for (mppwrite::VarEntry const& entry : entries) {
        if (entry.mid == uid) {
            keys.push_back(entry.field_id);
        }
    }
    return keys;
}

std::vector<std::uint8_t> var_payload(mppwrite::CfbDocument const& doc,
                                      std::string const& var_meta_path,
                                      std::string const& var2_path,
                                      std::uint32_t uid, std::uint32_t key) {
    std::vector<std::uint8_t> const var_meta = doc.read_stream(var_meta_path);
    std::vector<std::uint8_t> const var2 = doc.read_stream(var2_path);
    std::vector<std::uint32_t> const offsets =
        mppwrite::find_var_offsets(var_meta, key, uid);
    if (offsets.size() != 1) {
        return {};
    }
    return mppwrite::read_var_block(var2, offsets.front());
}

