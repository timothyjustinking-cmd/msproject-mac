    t.equal(g1.fixed2_meta - g0.fixed2_meta, std::size_t{53},
            "assignment add: Fixed2Meta +53");
    t.equal(g1.var_meta - g0.var_meta, std::size_t{48},
            "assignment add: VarMeta +4 entries");
    /* contour 76 + created 8 + two 16-byte blocks (20 each) = 124. */
    t.equal(g1.var2 - g0.var2, std::size_t{124},
            "assignment add: Var2Data + the four blocks");
    check_assignment_geometry(t, doc, g1.rows, "assignment add");

    std::vector<std::uint8_t> const fixed = doc.read_stream(kAsnFixed);
    std::size_t const row = 3 * 110;
