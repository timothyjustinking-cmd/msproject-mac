class TestContext {
  public:
    void check(bool condition, std::string const& what) {
        ++checks_;
        if (!condition) {
            ++failures_;
            std::cout << "FAIL: " << what << "\n";
        }
    }
    void equal(std::size_t actual, std::size_t expected, std::string const& what) {
        check(actual == expected, what + " (actual " + std::to_string(actual) +
                                      ", expected " + std::to_string(expected) + ")");
    }
    int report() const {
        std::cout << checks_ << " checks, " << failures_ << " failures\n";
        return failures_ == 0 ? 0 : 1;
    }

  private:
    int checks_ = 0;
    int failures_ = 0;
};

std::string join(std::string const& a, std::string const& b) {
    return a + "/" + b;
}

std::string out_path(std::string const& name) {
    return join(MPPWRITE_TEST_OUT, name);
}

std::vector<std::uint8_t> read_file(std::string const& path) {
    std::ifstream input(path, std::ios::binary);
    if (!input) {
        throw std::runtime_error("cannot open " + path);
    }
    input.seekg(0, std::ios::end);
    std::streamoff const length = input.tellg();
    input.seekg(0, std::ios::beg);
    std::vector<std::uint8_t> bytes(static_cast<std::size_t>(length));
    if (!bytes.empty()) {
        input.read(reinterpret_cast<char*>(bytes.data()),
                   static_cast<std::streamsize>(bytes.size()));
    }
    return bytes;
}

void write_file(std::string const& path, std::vector<std::uint8_t> const& bytes) {
    std::ofstream output(path, std::ios::binary | std::ios::trunc);
    if (!output) {
        throw std::runtime_error("cannot create " + path);
    }
    if (!bytes.empty()) {
        output.write(reinterpret_cast<char const*>(bytes.data()),
                     static_cast<std::streamsize>(bytes.size()));
    }
    if (!output) {
        throw std::runtime_error("cannot write " + path);
    }
}

bool file_exists(std::string const& path) {
    std::error_code error;
    return std::filesystem::is_regular_file(path, error);
}

std::uint64_t fnv1a64(std::vector<std::uint8_t> const& bytes) {
    std::uint64_t hash = 1469598103934665603ULL;
    for (std::uint8_t const byte : bytes) {
        hash ^= byte;
        hash *= 1099511628211ULL;
    }
    return hash;
}

std::string hex64(std::uint64_t value) {
    static char const* digits = "0123456789abcdef";
    std::string out(16, '0');
    for (std::size_t i = 0; i < 16; ++i) {
        out[15 - i] = digits[(value >> (4 * i)) & 0xFu];
    }
    return "0x" + out;
}

std::uint16_t u16_at(std::vector<std::uint8_t> const& b, std::size_t o) {
    return static_cast<std::uint16_t>(b[o] | (b[o + 1] << 8));
}

std::uint32_t u32_at(std::vector<std::uint8_t> const& b, std::size_t o) {
    return static_cast<std::uint32_t>(b[o]) |
           (static_cast<std::uint32_t>(b[o + 1]) << 8) |
           (static_cast<std::uint32_t>(b[o + 2]) << 16) |
           (static_cast<std::uint32_t>(b[o + 3]) << 24);
}

double f64_at(std::vector<std::uint8_t> const& b, std::size_t o) {
    double value = 0.0;
    std::memcpy(&value, b.data() + o, sizeof value);
    return value;
}

std::size_t stream_size(mppwrite::CfbDocument const& doc, std::string const& path) {
    return doc.has_stream(path) ? doc.read_stream(path).size() : 0;
}

std::vector<std::string> changed_streams(mppwrite::CfbDocument const& a,
                                         mppwrite::CfbDocument const& b) {
    std::vector<std::string> out;
    for (std::string const& path : a.stream_paths()) {
        if (!b.has_stream(path)) {
            out.push_back(path + " (missing)");
        } else if (a.read_stream(path) != b.read_stream(path)) {
            out.push_back(path);
        }
    }
    return out;
}

bool contains(std::vector<std::string> const& items, std::string_view wanted) {
    return std::find(items.begin(), items.end(), wanted) != items.end();
}

/* Every stream outside `allowed` must be byte-identical. */
void check_only_streams_changed(TestContext& t, mppwrite::CfbDocument const& before,
                                mppwrite::CfbDocument const& after,
                                std::array<char const*, 6> const& allowed,
                                std::string const& label) {
    std::vector<std::string> const changed = changed_streams(before, after);
    for (std::string const& path : changed) {
        bool ok = false;
        for (char const* name : allowed) {
            if (path == name) {
                ok = true;
                break;
            }
        }
        t.check(ok, label + ": unexpected stream changed: " + path);
    }
    std::size_t allowed_changed = 0;
    for (char const* name : allowed) {
        if (contains(changed, name)) {
            ++allowed_changed;
        }
    }
    t.check(allowed_changed > 0, label + ": no intended stream changed");
}

void check_214_untouched(TestContext& t, mppwrite::CfbDocument const& before,
                         mppwrite::CfbDocument const& after,
                         std::string const& label) {
    std::size_t compared = 0;
    for (std::string const& path : before.stream_paths()) {
        if (path.rfind("214/", 0) != 0) {
            continue;
        }
        ++compared;
        t.check(after.has_stream(path), label + ": 214/ stream vanished: " + path);
        if (after.has_stream(path)) {
            t.check(after.read_stream(path) == before.read_stream(path),
                    label + ": 214/ stream changed: " + path);
        }
    }
    t.check(compared > 0, label + ": no 214/ streams found");
}

template <typename Callable>
void expect_throw(TestContext& t, std::string const& label, Callable&& call,
                  std::string_view needle) {
    try {
        call();
    } catch (std::exception const& error) {
        std::string const message = error.what();
        t.check(message.find(needle) != std::string::npos,
                label + ": refusal message did not mention '" +
                    std::string(needle) + "' (got: " + message + ")");
        return;
    }
    t.check(false, label + ": no exception was thrown");
}

struct Fixture {
    std::string file;
    std::size_t bytes = 0;
    std::uint64_t fnv = 0;
    std::string note;
};

std::vector<Fixture>& fixtures() {
    static std::vector<Fixture> list;
    return list;
}

void emit(TestContext& t, mppwrite::CfbDocument const& doc, std::string const& name,
          std::string const& note) {
    std::string const path = out_path(name);
    doc.save(path);
    std::vector<std::uint8_t> const bytes = read_file(path);
    t.check(bytes == doc.to_bytes(), "emit " + name + ": saved bytes differ");
    Fixture fixture;
    fixture.file = name;
    fixture.bytes = bytes.size();
    fixture.fnv = fnv1a64(bytes);
    fixture.note = note;
    fixtures().push_back(fixture);

    std::error_code error;
    std::filesystem::create_directories(MPPWRITE_FIXTURE_MIRROR, error);
    write_file(join(MPPWRITE_FIXTURE_MIRROR, name), bytes);
}

void write_manifest(TestContext& t) {
    std::string json = "{\n  \"wave\": \"w54\",\n  \"generated_by\": "
                       "\"mppwrite_roundtrip_assignments\",\n  \"fixtures\": [\n";
    for (std::size_t i = 0; i < fixtures().size(); ++i) {
        Fixture const& fixture = fixtures()[i];
        json += "    {\"file\": \"" + fixture.file + "\", \"bytes\": " +
                std::to_string(fixture.bytes) + ", \"fnv1a64\": \"" +
                hex64(fixture.fnv) + "\", \"note\": \"" + fixture.note + "\"}";
        json += (i + 1 == fixtures().size()) ? "\n" : ",\n";
    }
    json += "  ]\n}\n";
    std::vector<std::uint8_t> const bytes(json.begin(), json.end());
    write_file(out_path("w54-manifest.json"), bytes);
    std::error_code error;
    std::filesystem::create_directories(MPPWRITE_FIXTURE_MIRROR, error);
    write_file(join(MPPWRITE_FIXTURE_MIRROR, "w54-manifest.json"), bytes);
    t.check(file_exists(out_path("w54-manifest.json")), "manifest was not written");
}

/* ---- resource table helpers -------------------------------------------- */

struct ResourceGeometry {
    std::size_t rows = 0;
    std::size_t fixed = 0;
    std::size_t meta = 0;
    std::size_t fixed2 = 0;
    std::size_t fixed2_meta = 0;
    std::size_t var_meta = 0;
    std::size_t var2 = 0;
};

ResourceGeometry resource_geometry(mppwrite::CfbDocument const& doc) {
    ResourceGeometry out;
    out.fixed = stream_size(doc, kRscFixed);
    out.rows = out.fixed >= 48 ? (out.fixed - 48) / 172 : 0;
    out.meta = stream_size(doc, kRscMeta);
    out.fixed2 = stream_size(doc, kRscFixed2);
    out.fixed2_meta = stream_size(doc, kRscFixed2Meta);
    out.var_meta = stream_size(doc, kRscVarMeta);
    out.var2 = stream_size(doc, kRscVar2);
    return out;
}

/* Every size/count word the resource table must maintain. */
void check_resource_geometry(TestContext& t, mppwrite::CfbDocument const& doc,
                             std::size_t expected_rows, std::string const& label) {
    ResourceGeometry const g = resource_geometry(doc);
    t.equal(g.rows, expected_rows, label + ": FixedData rows");
    t.equal(g.fixed, 48 + 172 * expected_rows, label + ": FixedData size");
    t.equal(g.meta, 16 + 37 * (expected_rows + 3), label + ": FixedMeta size");
    t.equal(g.fixed2, 40 * (expected_rows + 3), label + ": Fixed2Data size");
    t.equal(g.fixed2_meta, 16 + 51 * (expected_rows + 3),
            label + ": Fixed2Meta size");
    std::vector<std::uint8_t> const meta = doc.read_stream(kRscMeta);
    std::vector<std::uint8_t> const fixed2_meta = doc.read_stream(kRscFixed2Meta);
    t.equal(u32_at(meta, 0), 0xFADFADBAu, label + ": FixedMeta magic");
    t.equal(u32_at(meta, 8), expected_rows + 3, label + ": FixedMeta +8 entries");
    t.equal(u32_at(meta, 12), g.fixed, label + ": FixedMeta +12 FixedData size");
    t.equal(u32_at(fixed2_meta, 0), 0xFADFADBAu, label + ": Fixed2Meta magic");
    t.equal(u32_at(fixed2_meta, 8), expected_rows + 3,
            label + ": Fixed2Meta +8 entries");
    t.equal(u32_at(fixed2_meta, 12), g.fixed2,
            label + ": Fixed2Meta +12 Fixed2Data size");
    std::vector<std::uint8_t> const var_meta = doc.read_stream(kRscVarMeta);
    t.equal((var_meta.size() - 24) % 12, std::size_t{0},
            label + ": VarMeta is 24 + 12*k");
    t.equal(u32_at(var_meta, 8), (var_meta.size() - 24) / 12,
            label + ": VarMeta declared entry count");
    t.equal(static_cast<std::size_t>(u32_at(var_meta, 0x14)), g.var2,
            label + ": VarMeta +0x14 Var2Data size");
    for (std::size_t row = 0; row < expected_rows; ++row) {
        t.equal(u32_at(meta, 16 + (row + 3) * 37 + 4), 48 + row * 172,
                label + ": resource FixedMeta entry " + std::to_string(row) +
                    " offset");
        t.equal(u32_at(fixed2_meta, 16 + (row + 3) * 51 + 4), (row + 3) * 40,
                label + ": resource Fixed2Meta entry " + std::to_string(row) +
                    " offset");
    }
    t.check(mppwrite::check_table(doc).empty(),
            label + ": Task check_table: " + mppwrite::check_table(doc));
    t.check(doc.check().empty(), label + ": container check: " + doc.check());
}

