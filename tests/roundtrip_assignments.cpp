/*
 * roundtrip_assignments.cpp -- W54: add a TBkndRsc resource row and add/delete a
 * TBkndAssn assignment row, proving every fact from the bytes on disk.
 *
 * CLAIM UNDER TEST.  A resource row is not a single 172-byte record: Project's
 * own add (corpus/probe/w12-assignadd.mpp, built from
 * tests/data/synthetic-base.mpp) grew SIX TBkndRsc streams:
 *
 *   FixedData   48 + 172 * rows         new row = clone of the last live row
 *                                       with ID, UniqueID and +154 changed
 *   FixedMeta   16 + 37 * (rows + 3)    one entry: +0 state, +2 field count (5),
 *                                       +4 row offset, +12 type flags (bit 0x10
 *                                       = Work)
 *   Fixed2Data  40 * (rows + 3)         record: 16-byte identity, f64 row + 1,
 *                                       the same identity again
 *   Fixed2Meta  16 + 51 * (rows + 3)    entry: +4 record offset, +8 type flags
 *                                       (bit 0x10 = Cost)
 *   VarMeta     24 + 12 * k             five entries for the new uid:
 *                                       0x0c400001 Name, 0x0c400002 Initials,
 *                                       0x0c400055 u32, 0x0c4002d6 date,
 *                                       0x0c4002e3 16 zero bytes
 *   Var2Data    length-prefixed blocks  the five payloads, appended
 *
 * An assignment row is 110 bytes (FixedData has no header) with
 * FixedMeta 16 + 34*n, Fixed2Data 48*n, Fixed2Meta 16 + 53*n and FOUR VarMeta
 * entries (0x0f400031 flat contour, 0x0f40027a Created, 0x0f400199 and
 * 0x0f40019b 16-byte blocks).  A delete is a tombstone: FixedMeta entry +0 = 0x02,
 * +2 = 0, header +4 |= 0x02, no stream changes size.
 *
 * For every operation the test asserts, from the written file:
 *   1. the exact stream deltas and every header count/size word;
 *   2. the new row/entries/identities/blocks byte for byte, or the tombstone;
 *   3. only the intended table's streams changed, every 214/ stream is
 *      byte-identical;
 *   4. the re-read document re-emits byte-identically and `check_table` (Task)
 *      and `CfbDocument::check()` are clean;
 *   5. the independent core/mpp reader returns the Project-visible resources and
 *      assignments (when the top-level build provides it);
 *   6. refusals fire and leave `doc` and the output path untouched.
 *
 * NO CORPUS NEEDED: tests/data/synthetic-base.mpp has one resource (uid 1,
 * "Crew") and three unassigned placeholder assignment rows (task uids 1/2/3,
 * null resource), which is enough to exercise both adds and the delete.  When
 * corpus/probe is present, the coordinator's measured w12-assignadd.mpp is used
 * as a control.
 *
 * OUTPUT (build tree, git-ignored), regenerated by running this binary:
 *   w54-resource.mpp            synthetic-base + resource uid 2 ("R54", Work 100 %)
 *   w54-assignment.mpp          that file + assignment uid 4 (task 1 / resource 2)
 *   w54-assignment-deleted.mpp  that file after tombstoning assignment uid 4
 *   w54-manifest.json           size + FNV-1a 64 per file
 * written to ${MPPWRITE_TEST_OUT} and mirrored to ${MPPWRITE_FIXTURE_MIRROR}.
 */

