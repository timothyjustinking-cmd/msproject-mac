/* ---- (a) add a resource ------------------------------------------------- */

void test_resource_add(TestContext& t) {
    mppwrite::CfbDocument doc = mppwrite::CfbDocument::from_file(source_path());
    mppwrite::CfbDocument const before = mppwrite::CfbDocument::from_file(source_path());
    ResourceGeometry const g0 = resource_geometry(doc);

    mppwrite::ResourceSpec spec;
    spec.name = "R54";
    spec.max_units_percent = 100.0;
    spec.kind = mppwrite::ResourceKind::work;
    mppwrite::AddedResource const added =
        mppwrite::add_resource_row(doc, spec, out_path("w54-resource.mpp"));

    t.equal(added.uid, 2, "resource add: uid 2 (largest uid 1 + 1)");
    t.equal(added.id, 2, "resource add: ID 2 (largest live ID 1 + 1)");
    t.equal(added.row, 2, "resource add: row 2 (rows were 2)");
    t.check(added.name == "R54", "resource add: name in the receipt");
    t.check(added.initials == "R", "resource add: initials derived from the name");

    ResourceGeometry const g1 = resource_geometry(doc);
    t.equal(g1.fixed - g0.fixed, std::size_t{172}, "resource add: FixedData +172");
    t.equal(g1.meta - g0.meta, std::size_t{37}, "resource add: FixedMeta +37");
    t.equal(g1.fixed2 - g0.fixed2, std::size_t{40}, "resource add: Fixed2Data +40");
    t.equal(g1.fixed2_meta - g0.fixed2_meta, std::size_t{51},
            "resource add: Fixed2Meta +51");
    t.equal(g1.var_meta - g0.var_meta, std::size_t{60},
            "resource add: VarMeta +5 entries");
    /* Name "R54" (12 B block), Initials "R" (8), rate 8, date 8, blob 20. */
    t.equal(g1.var2 - g0.var2, std::size_t{56},
            "resource add: Var2Data + the five payload blocks");
    t.equal(g1.rows, g0.rows + 1, "resource add: one more row");
    check_resource_geometry(t, doc, g1.rows, "resource add");

    /* The row is the last live row's clone with ID/uid/MaxUnits/+154 changed. */
    std::vector<std::uint8_t> const fixed = doc.read_stream(kRscFixed);
    std::size_t const new_offset = 48 + 2 * 172;
    std::vector<std::uint8_t> const template_row(
        fixed.begin() + static_cast<std::ptrdiff_t>(48 + 172),
        fixed.begin() + static_cast<std::ptrdiff_t>(48 + 2 * 172));
    std::vector<std::uint8_t> new_row(fixed.begin() +
                                         static_cast<std::ptrdiff_t>(new_offset),
                                     fixed.begin() + static_cast<std::ptrdiff_t>(
                                                        new_offset + 172));
    t.equal(u32_at(new_row, 0), 2, "resource add: row ID");
    t.equal(u32_at(new_row, 4), 2, "resource add: row UniqueID");
    t.check(f64_at(new_row, 8) == 10000.0, "resource add: MaxUnits 100 % (x100)");
    t.equal(u16_at(new_row, 154), u16_at(template_row, 154) + 1,
            "resource add: per-row counter is template + 1");
    for (std::size_t i = 0; i < 172; ++i) {
        if (i == 0 || i == 1 || i == 4 || i == 5 || i == 154 || i == 155) {
            continue; /* ID, UniqueID and the counter are the intended changes */
        }
        t.check(new_row[i] == template_row[i],
                "resource add: row byte +" + std::to_string(i) +
                    " is the template's");
    }

    std::vector<std::uint8_t> const meta = doc.read_stream(kRscMeta);
    std::size_t const entry = 16 + 5 * 37;
    t.equal(meta[entry], 0, "resource add: FixedMeta entry state 0 (live)");
    t.equal(u16_at(meta, entry + 2), 5,
            "resource add: FixedMeta entry field count 5");
    t.equal(u32_at(meta, entry + 4), new_offset,
            "resource add: FixedMeta entry names the new row");
    t.equal(meta[entry + 12], 0x5C,
            "resource add: FixedMeta +12 is Project's measured Work byte 0x5c");
    std::vector<std::uint8_t> const fixed2_meta = doc.read_stream(kRscFixed2Meta);
    std::size_t const f2_entry = 16 + 5 * 51;
    t.equal(u32_at(fixed2_meta, f2_entry + 4), 5 * 40,
            "resource add: Fixed2Meta entry names record 5");
    t.check((fixed2_meta[f2_entry + 8] & 0x10) == 0,
            "resource add: Fixed2Meta +8 bit 0x10 clear for Work");

    std::vector<std::uint8_t> const fixed2 = doc.read_stream(kRscFixed2);
    t.equal(fixed2.size(), std::size_t{240}, "resource add: Fixed2Data is 240 B");
    std::array<std::uint8_t, 16> const identity = [&fixed2]() {
        std::array<std::uint8_t, 16> out{};
        std::copy(fixed2.begin() + static_cast<std::ptrdiff_t>(5 * 40),
                  fixed2.begin() + static_cast<std::ptrdiff_t>(5 * 40 + 16),
                  out.begin());
        return out;
    }();
    std::array<std::uint8_t, 16> const identity_copy = [&fixed2]() {
        std::array<std::uint8_t, 16> out{};
        std::copy(fixed2.begin() + static_cast<std::ptrdiff_t>(5 * 40 + 24),
                  fixed2.begin() + static_cast<std::ptrdiff_t>(5 * 40 + 40),
                  out.begin());
        return out;
    }();
    t.check(identity == identity_copy,
            "resource add: Fixed2Data record holds its identity twice");
    t.check(f64_at(fixed2, 5 * 40 + 16) == 3.0,
            "resource add: Fixed2Data ordinal is row + 1 (3.0)");
    t.check(identity != std::array<std::uint8_t, 16>{},
            "resource add: Fixed2Data identity is not all zero");

    std::vector<std::uint32_t> const keys = var_keys_for(doc, kRscVarMeta, 2);
    std::array<std::uint32_t, 5> const expected = {0x0C400001u, 0x0C400002u,
                                                   0x0C400055u, 0x0C4002D6u,
                                                   0x0C4002E3u};
    t.equal(keys.size(), expected.size(),
            "resource add: five variable entries for the new uid");
    if (keys.size() == expected.size()) {
        for (std::size_t i = 0; i < expected.size(); ++i) {
            t.equal(keys[i], expected[i],
                    "resource add: variable entry " + std::to_string(i) + " key");
        }
    }
    t.check(mppwrite::decode_utf16z(var_payload(doc, kRscVarMeta, kRscVar2, 2,
                                                0x0C400001u)) == "R54",
            "resource add: Name block decodes to R54");
    t.check(mppwrite::decode_utf16z(var_payload(doc, kRscVarMeta, kRscVar2, 2,
                                                0x0C400002u)) == "R",
            "resource add: Initials block decodes to R");
    std::vector<std::uint8_t> const rate =
        var_payload(doc, kRscVarMeta, kRscVar2, 2, 0x0C400055u);
    t.check(rate.size() == 4 && u32_at(rate, 0) == 2,
            "resource add: 0x0c400055 payload is the template's u32 2");
    std::vector<std::uint8_t> const blob =
        var_payload(doc, kRscVarMeta, kRscVar2, 2, 0x0C4002E3u);
    t.check(blob.size() == 16 &&
                std::all_of(blob.begin(), blob.end(),
                            [](std::uint8_t byte) { return byte == 0; }),
            "resource add: 0x0c4002e3 payload is 16 zero bytes");
    std::vector<std::uint8_t> const stamp =
        var_payload(doc, kRscVarMeta, kRscVar2, 2, 0x0C4002D6u);
    t.check(stamp.size() == 4, "resource add: 0x0c4002d6 payload is 4 bytes");

    check_only_streams_changed(t, before, doc, resource_streams(), "resource add");
    check_214_untouched(t, before, doc, "resource add");
    t.check(doc.to_bytes() == read_file(out_path("w54-resource.mpp")),
            "resource add: the document equals the file on disk");

    mppwrite::CfbDocument const reread =
        mppwrite::CfbDocument::from_file(out_path("w54-resource.mpp"));
    t.check(reread.to_bytes() == doc.to_bytes(),
            "resource add: the written file re-emits byte-identically");
    emit(t, doc, "w54-resource.mpp",
         "synthetic-base + resource uid 2 R54 Work 100 %");
}

