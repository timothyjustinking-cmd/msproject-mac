    t.equal(u32_at(doc.read_stream(kMeta), 4), 0x06,
            "add-after-delete: header +4 has bit 0x02 after the delete");
    mppwrite::AddedLink const readded =
        mppwrite::add_task_link(doc, 1, 3, mppwrite::kLinkTypeSS, 4800,
                                out_path("w52-aad-3.mpp"));
    t.equal(readded.uid, 3, "add-after-delete: uid is max + 1");
    check_link_geometry(t, doc, 3, "add-after-delete");
    t.equal(u32_at(doc.read_stream(kMeta), 4), 0x06,
            "add-after-delete: the delete flag is not cleared by an add");
    t.equal(live_link_count(doc), 2, "add-after-delete: two live links");
    std::vector<std::uint8_t> const fixed2_meta = doc.read_stream(kFixed2Meta);
    t.equal(fixed2_meta[16 + 2 * 9 + 8], 0x0F,
            "add-after-delete: the first LIVE link into a successor is 0x0f");
    LinkRow const row = read_link_row(doc, 2);
    t.equal(row.uid, 3, "add-after-delete: new row uid");
    t.equal(row.state, 0x00, "add-after-delete: new row is live");
    t.check(doc.read_stream(kFixed2) != before_delete.read_stream(kFixed2),
            "add-after-delete: Fixed2Data grew");
