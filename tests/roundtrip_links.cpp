/*
 * roundtrip_links.cpp -- W52: add and delete TBkndCons link rows, prove them
 * from the bytes on disk.
 *
 * CLAIM UNDER TEST.  A link row is NOT just a 20-byte FixedData record: Project
 * writes FOUR TBkndCons streams when it adds a link (measured on
 * corpus/probe/link1.mpp and the coordinator's corpus/probe/w12-linkadd.mpp):
 *
 *   FixedData   20 * rows                 uid, pred uid, succ uid, u16 type,
 *                                         i32 lag ticks, u16 lag format
 *   FixedMeta   16 + 10 * rows            one 10-byte entry per row:
 *                                         +0 state, +2 field count (0),
 *                                         +4 row byte offset, +8/+9 = dd 00
 *   Fixed2Data  48 * rows                 three 16-byte identities per link:
 *                                         link, predecessor task, successor task
 *   Fixed2Meta  16 + 9 * rows             one 9-byte entry per row:
 *                                         +0..3 = 0, +4 record offset,
 *                                         +8 = 0x0f on every measured add
 *
 * The wave-47 comment here used to call +8 "0x0f (first link into that
 * successor) / 0x07 (a later one)".  Wave 29 falsified that (R29-7): +8 is the
 * successor's driving state, 0x07 once it has progress, and the percent-mid25
 * control's FIRST of three links into distinct successors is 0x07.  W30-0.7
 * therefore makes add_task_link refuse a successor that already has a live
 * incoming link or has progress; every add this test performs is a first link
 * into a 0 % successor, and every flag it writes is 0x0f.
 *
 * A delete is a TOMBSTONE: FixedMeta entry +0 = 0x02, +2 = 0, header +4 |= 0x02
 * (the same contract W48's task-delete cascade implements), and no stream changes
 * size.  FixedData, Fixed2Data and Fixed2Meta keep every byte.
 *
 * For every operation the test asserts, from the written file:
 *   1. all four sizes and every header count/size word;
 *   2. the new row/entries/identities byte for byte, or the tombstone state;
 *   3. only the intended TBkndCons streams changed, every 214/ stream is
 *      byte-identical;
 *   4. the re-read document equals the file and re-emits byte-identically;
 *   5. `check_table` (Task table) and `CfbDocument::check()` are clean;
 *   6. the independent core/mpp reader returns the Project-visible link list
 *      (when the top-level build provides it);
 *   7. refusals fire and leave `doc` and the output path untouched.
 *
 * NO CORPUS NEEDED: tests/data/synthetic-base.mpp has three tasks and an empty
 * link table (FixedData 0 B, FixedMeta 16 B, Fixed2Data 0 B, Fixed2Meta 16 B), so
 * every core case is corpus-free.  When corpus/probe is present the measured
 * fixtures (link1.mpp, w12-linkadd.mpp, w11-linkdelete-pre/-post.mpp) are read as
 * controls.
 *
 * OUTPUT (build tree, git-ignored), regenerated by running this binary:
 *   w52-links.mpp          two links: 1->2 FS+0 and 1->3 SS+1d
 *   w52-links-deleted.mpp  the same file after deleting link uid 2 (the last)
 *   w52-manifest.json      size + FNV-1a 64 per file
 * written to ${MPPWRITE_TEST_OUT} and mirrored to ${MPPWRITE_FIXTURE_MIRROR}.
 */

