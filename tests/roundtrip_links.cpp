/* ---- (c) refusals ------------------------------------------------------- */

void test_refusals(TestContext& t) {
    mppwrite::CfbDocument doc = synthetic_source();
    (void)mppwrite::add_task_link(doc, 1, 2, mppwrite::kLinkTypeFS, 0,
                                  out_path("w52-ref-base.mpp"));
    std::string const missing = out_path("w52-ref-should-not-exist.mpp");
    std::error_code ignored;
    std::filesystem::remove(missing, ignored);

    auto expect_refusal = [&](auto&& fn, std::string_view needle,
                              std::string const& what) {
        mppwrite::CfbDocument const before = doc;
        expect_error(t, fn, needle, what);
        t.check(doc.to_bytes() == before.to_bytes(),
                what + ": the document changed on refusal");
        t.check(!file_exists(missing), what + ": the output file was created");
    };

    expect_refusal(
        [&] { mppwrite::add_task_link(doc, 1, 1, 1, 0, missing); },
        "self-link", "self-link refused");
    expect_refusal(
        [&] { mppwrite::add_task_link(doc, 1, 2, 1, 0, missing); },
        "duplicate", "duplicate relation refused");
    expect_refusal(
        [&] { mppwrite::add_task_link(doc, 1, 2, 1, 99, missing); },
        "duplicate", "duplicate relation with a different lag refused");
    /* W30-0.7 (R29-7): the doc already has 1 -> 2, so 3 -> 2 would be a second
     * incoming link -- the shape whose Fixed2Meta byte the old rule fabricated. */
    expect_refusal(
        [&] { mppwrite::add_task_link(doc, 3, 2, 1, 0, missing); },
        "incoming link", "second incoming link refused (W30-0.7)");
    expect_refusal(
        [&] { mppwrite::add_task_link(doc, 99, 2, 1, 0, missing); },
        "live task row", "unknown predecessor refused");
    expect_refusal(
        [&] { mppwrite::add_task_link(doc, 1, 99, 1, 0, missing); },
        "live task row", "unknown successor refused");
    expect_refusal(
        [&] { mppwrite::add_task_link(doc, 0, 2, 1, 0, missing); },
        "project row", "uid 0 endpoint refused");
    expect_refusal(
        [&] { mppwrite::add_task_link(doc, 1, 3, 4, 0, missing); },
        "link type", "type 4 refused");
    expect_refusal(
        [&] {
            mppwrite::add_task_link(doc, 1, 3, 1,
                                    mppwrite::kMaxLinkLagTicks + 1, missing);
        },
        "outside", "out-of-range lag refused");

    /* W30-0.7 (R29-7): the second shape the old rule got wrong -- a link into a
     * progressed successor.  Wave 29 measured +8 as the successor's driving
     * state (0x07 once it has progress), and no Project save pair adds a link
     * into a progressed task.  Task 1 is patched to 40 % in its FixedData. */
    {
        mppwrite::CfbDocument progressed = synthetic_source();
        mppwrite::TaskTable table = mppwrite::TaskTable::from_document(progressed);
        table.set_u16(table.row_for_uid(1), mppwrite::task_row::kPercentComplete, 40);
        table.store_into(progressed);
        mppwrite::CfbDocument const before = progressed;
        expect_error(
            t,
            [&] { mppwrite::add_task_link(progressed, 2, 1, 1, 0, missing); },
            "progress", "progressed successor refused (W30-0.7)");
        t.check(progressed.to_bytes() == before.to_bytes(),
                "progressed successor: the document changed on refusal");
        t.check(!file_exists(missing),
                "progressed successor: the output file was created");
    }

    /* A damaged Cons table: each refusal leaves the document untouched. */
    {
        mppwrite::CfbDocument damaged = doc;
        std::vector<std::uint8_t> meta = damaged.read_stream(kMeta);
        put_u32_at(meta, 8, 99);
        damaged.replace_stream(kMeta, meta);
        mppwrite::CfbDocument const before = damaged;
        expect_error(
            t,
            [&] { mppwrite::add_task_link(damaged, 1, 3, 1, 0, missing); },
            "damaged", "stale FixedMeta entry count refused");
        t.check(damaged.to_bytes() == before.to_bytes(),
                "damaged count: the document changed on refusal");
    }
    {
        mppwrite::CfbDocument damaged = doc;
        std::vector<std::uint8_t> fixed = damaged.read_stream(kFixed);
        fixed.push_back(0);
        damaged.replace_stream(kFixed, fixed);
        expect_error(
            t,
            [&] { mppwrite::add_task_link(damaged, 1, 3, 1, 0, missing); },
            "geometry", "truncated FixedData refused");
    }
    {
        mppwrite::CfbDocument damaged = doc;
        std::vector<std::uint8_t> fixed2_meta = damaged.read_stream(kFixed2Meta);
        fixed2_meta.push_back(0);
        damaged.replace_stream(kFixed2Meta, fixed2_meta);
        expect_error(
            t,
            [&] { mppwrite::add_task_link(damaged, 1, 3, 1, 0, missing); },
            "damaged", "corrupt Fixed2Meta size refused");
    }

    /* Delete refusals. */
    expect_refusal(
        [&] { mppwrite::delete_task_link(doc, 0, missing); },
        "project row", "delete uid 0 refused");
    expect_refusal(
        [&] { mppwrite::delete_task_link(doc, 99, missing); },
        "no link row", "delete unknown link uid refused");
    {
        mppwrite::CfbDocument deleted = doc;
        (void)mppwrite::delete_task_link(deleted, 1, out_path("w52-ref-del.mpp"));
        expect_error(
            t,
            [&] { mppwrite::delete_task_link(deleted, 1, missing); },
            "already a tombstone", "delete an already-tombstoned link refused");
        t.equal(live_link_count(deleted), 0, "refusal control: link 1 is gone");
    }

    /* A refused ADD must not leave a pre-existing output file modified. */
    {
        std::string const existing = out_path("w52-ref-existing.mpp");
        mppwrite::CfbDocument source = synthetic_source();
        (void)mppwrite::add_task_link(source, 1, 2, mppwrite::kLinkTypeFS, 0,
                                      existing);
        std::vector<std::uint8_t> const bytes_before = read_file(existing);
        expect_error(
            t,
            [&] { mppwrite::add_task_link(source, 1, 1, 1, 0, existing); },
            "self-link", "refusal with an existing output path");
        t.check(read_file(existing) == bytes_before,
                "refusal with an existing output path: the file changed");
    }
}

