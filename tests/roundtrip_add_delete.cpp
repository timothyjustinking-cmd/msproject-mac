/* ---- (c) add a row with a caller-supplied mid-range uid ------------------ */
void test_add_mid_uid(TestContext& t) {
    std::string const source = join(MPPWRITE_TEST_DATA, "synthetic-base.mpp");
    mppwrite::CfbDocument doc = mppwrite::CfbDocument::from_file(source);
    /* Make uid 4 free but NOT the largest: re-key the third task from uid 3 to
     * uid 5 (its row, its VarMeta entries and its assignment).  This is the case
     * where Project's contiguous-uid-group rule matters for `add_task_row`. */
    std::vector<std::uint8_t> fixed = doc.read_stream(kFixed);
    put_u32_at(fixed, mppwrite::task_row_offset(3) + 4, 5);
    doc.replace_stream(kFixed, fixed);
    std::vector<std::uint8_t> var_meta = doc.read_stream(kVarMeta);
    for (mppwrite::VarEntry const& entry : mppwrite::read_var_entries(var_meta)) {
        if (entry.mid == 3) {
            put_u32_at(var_meta, 24 + entry.index * 12, 5);
        }
    }
    doc.replace_stream(kVarMeta, var_meta);
    std::vector<std::uint8_t> assn = doc.read_stream(assn_stream("FixedData"));
    put_u32_at(assn, 2 * 110 + 4, 5);
    doc.replace_stream(assn_stream("FixedData"), assn);

    mppwrite::NewTaskRow task;
    task.name = "W48 Mid UID";
    task.uid = 4;
    mppwrite::AddedRow const added =
        mppwrite::add_task_row(doc, task, out_path("w48-add-mid-uid.mpp"));
    t.check(added.uid == 4 && added.row == 4, "mid uid: uid 4 appended at row 4");
    t.check(mppwrite::read_task_name(doc, 4) == task.name,
            "mid uid: the new Name reads back");

    /* Project keeps each uid's entries contiguous (W48 gate); the 8 new entries
     * must be inserted between uid 2's and uid 5's groups, not at the end. */
    std::vector<mppwrite::VarEntry> const entries =
        mppwrite::read_var_entries(doc.read_stream(kVarMeta));
    std::vector<std::uint32_t> sequence;
    for (mppwrite::VarEntry const& entry : entries) {
        sequence.push_back(entry.mid);
    }
    std::vector<std::uint32_t> expected;
    expected.insert(expected.end(), 9, 0u);  /* project row */
    expected.insert(expected.end(), 11, 1u);
    expected.insert(expected.end(), 11, 2u);
    expected.insert(expected.end(), 8, 4u); /* the new uid, inside its group */
    expected.insert(expected.end(), 11, 5u);
    t.check(sequence == expected,
            "mid uid: VarMeta is not grouped [0]*9 [1]*11 [2]*11 [4]*8 [5]*11");
    check_table_headers(t, doc, 5, "w48-add-mid-uid.mpp");
    emit(t, doc, "w48-add-mid-uid.mpp",
         "synthetic-base with task 3 re-keyed to uid 5, then add uid 4: its 8 "
         "entries are inserted inside uid 4's group, not appended at the end");
}

