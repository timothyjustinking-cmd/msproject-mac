    for (mpp::SkippedRow const& row : document.skipped_rows) {
        tombstone_reported = tombstone_reported || row.uid == 2;
    }
    t.check(tombstone_reported, "cascade synthetic: core/mpp reports uid 2 as a "
                                "tombstoned row");
#endif
