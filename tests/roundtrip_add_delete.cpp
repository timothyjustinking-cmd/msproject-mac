/* FixedMeta entry index naming `row` in a headerless table (Link 20/10,
 * Assignment 110/34): the entry's +4 word is `row * row_size`. */
int dep_entry_for_row(std::vector<std::uint8_t> const& meta, std::size_t entry_size,
                      std::size_t row_size, std::size_t row) {
    std::uint32_t const wanted = static_cast<std::uint32_t>(row * row_size);
    std::size_t const entries = (meta.size() - 16) / entry_size;
    for (std::size_t i = 0; i < entries; ++i) {
        if (u32_at(meta, 16 + i * entry_size + 4) == wanted) {
            return static_cast<int>(i);
        }
    }
    return -1;
}

std::uint32_t dep_header_flags(std::vector<std::uint8_t> const& meta) {
    return u32_at(meta, 4);
}

