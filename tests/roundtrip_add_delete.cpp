/*
 * roundtrip_add_delete.cpp -- W45/W48: append a Task row, tombstone a row, and
 * cascade the delete into the link and assignment tables.
 *
 * CLAIM UNDER TEST.  One task row is six streams that must grow together, and a
 * delete is a tombstone that must not shrink any of them:
 *
 *   FixedData  +202                     FixedMeta  +47 (entry +0 = 0, +2 = 8)
 *   Fixed2Data +64                      Fixed2Meta +96 (entry +8 = 0x7f)
 *   VarMeta    +96 (8 entries)          Var2Data  + the 8 new blocks
 *
 * A delete sets FixedMeta entry +0 = 0x02 and +2 = 0, renumbers later live rows'
 * ID down by one, removes the uid's VarMeta entries, leaves every stream size
 * unchanged and leaves Fixed2Data/Fixed2Meta/Var2Data byte-identical.
 *
 * W48 CASCADE (measured, docs/analysis/oracle/w11-oracle.md §2): a task delete
 * also tombstones every TBkndCons row whose predecessor OR successor is the uid
 * and every TBkndAssn row whose task uid is, with the same entry contract
 * (+0 = 0x02, +2 = 0) and the same header +4 bit 0x02 in each table.  No
 * dependent row or FixedData byte moves.  `w48-del-cascade.mpp` (from Project's
 * own w11-linkdelete-pre.mpp) is compared byte-for-byte with Project's
 * w11-linkdelete-post.mpp for the link table -- the strongest available check
 * without the oracle.
 *
 * The test does not trust the mapping.  For every operation it asserts:
 *   1. the stream sizes and every header count/size word, from the bytes;
 *   2. the new/tombstoned FixedMeta, Fixed2Meta, VarMeta entries and blocks;
 *   3. only the expected table streams changed, and every 214/ stream is
 *      byte-identical;
 *   4. the re-read document equals the file on disk and re-emits identically;
 *   5. `check_table` is empty and `CfbDocument::check()` is clean;
 *   6. the independent `core/mpp` reader returns the Project-visible task count,
 *      IDs and UniqueIDs (never names -- names are not needed for the claim);
 *   7. the refusals fire (uid 0, duplicate uid, unknown/already-deleted uid,
 *      broken size identity, a pre-existing dead link endpoint without
 *      `allow_dangling`, an empty name).
 *
 * NO CORPUS NEEDED for the core cases: they are built from
 * tests/data/synthetic-base.mpp (a committed, non-client fixture, byte-identical
 * to corpus/probe/base.mpp).  Its TBkndCons table is empty, so
 * `make_link_source` appends two link rows (1->2, 2->3) for the cascade test.
 * The probe fixtures used when present (w10-adddel-base.mpp, w10-adddel-back.mpp,
 * w11-linkdelete-pre.mpp, w11-linkdelete-post.mpp) are Project's own files and
 * are only read.
 *
 * OUTPUT (build tree, git-ignored), deterministic names, regenerated by running
 * the test binary: w45-add.mpp, w45-add2.mpp, w45-add-values.mpp,
 * w45-del-middle.mpp, w45-del-last.mpp, w45-add-before-delete.mpp,
 * w45-add-back.mpp, w45-append-after-delete.mpp, w48-del-cascade-synthetic.mpp,
 * w48-cascade-default.mpp, w48-cascade-dangling.mpp, w48-cascade-endpoint.mpp,
 * the optional w45-del-probe-middle.mpp and w48-del-cascade.mpp, and
 * w45-manifest.json (size + FNV-1a 64 per file).  Each file is written to
 * ${MPPWRITE_TEST_OUT} and mirrored to core/mppwrite/build/vs-w48/test-out/ for
 * the coordinator's oracle run.
 */

