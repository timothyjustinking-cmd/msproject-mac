/* ---- (d) delete a middle row: tombstone + ID renumber + VarMeta removal ---- */
void test_delete_middle(TestContext& t) {
    std::string const source = join(MPPWRITE_TEST_DATA, "synthetic-base.mpp");
    mppwrite::CfbDocument doc = mppwrite::CfbDocument::from_file(source);
    mppwrite::CfbDocument const before = doc;
    mppwrite::TaskTable const table0 = mppwrite::TaskTable::from_document(doc);
    t.equal(table0.row_id(3), std::uint32_t{3}, "delete middle: uid 3 starts with ID 3");

    mppwrite::DeleteOptions options;
    options.allow_dangling = true; /* the synthetic file's placeholder assignments */
    mppwrite::DeletedRow const deleted =
        mppwrite::delete_task_row(doc, 2, out_path("w45-del-middle.mpp"), options);
    t.check(deleted.uid == 2 && deleted.row == 2 && deleted.id == 2,
            "delete middle: report names row 2 / uid 2 / ID 2");
    t.equal(deleted.var_entries_removed, 11,
            "delete middle: uid 2's 11 VarMeta entries were removed");
    t.check(!deleted.warnings.empty(),
            "delete middle: the opt-in dangling assignment was not warned about");

    mppwrite::TaskTable const table1 = mppwrite::TaskTable::from_document(doc);
    t.equal(table1.rows(), std::size_t{4}, "delete middle: row count is unchanged");
    t.equal(table1.uid(2), std::uint32_t{2}, "delete middle: the slot still holds uid 2");
    t.equal(table1.row_id(3), std::uint32_t{2}, "delete middle: uid 3's ID is renumbered 3 -> 2");

    std::vector<std::uint8_t> const meta = doc.read_stream(kMeta);
    int const entry = meta_entry_for_row(meta, 2);
    t.check(entry >= 0, "delete middle: the tombstoned row keeps its FixedMeta entry");
    if (entry >= 0) {
        std::size_t const base = 16 + static_cast<std::size_t>(entry) * 47;
        t.equal(meta[base], 0x02, "delete middle: FixedMeta entry +0 is 0x02");
        t.equal(u16_at(meta, base + 2), 0, "delete middle: FixedMeta entry +2 is 0");
    }
    t.equal(fixed_meta_header_flags(doc), 0x06u,
            "delete middle: FixedMeta header +4 has the deleted-rows bit (4 -> 6)");

    std::vector<std::uint8_t> const var_meta = doc.read_stream(kVarMeta);
    t.equal(mppwrite::read_var_entries(var_meta).size(), 31,
            "delete middle: VarMeta has 42 - 11 entries");
    t.check(mppwrite::read_task_name(doc, 2).empty(),
            "delete middle: uid 2 has no Name entry any more");

    /* Every stream keeps its size; only FixedData/FixedMeta/VarMeta change. */
    for (char const* name : {"FixedData", "FixedMeta", "Fixed2Data", "Fixed2Meta",
                             "Var2Data"}) {
        t.equal(doc.read_stream(join("114/TBkndTask", name)).size(),
                before.read_stream(join("114/TBkndTask", name)).size(),
                std::string("delete middle: ") + name + " size is unchanged");
    }
    t.equal(doc.read_stream(kVarMeta).size(),
            before.read_stream(kVarMeta).size() - 11 * 12,
            "delete middle: VarMeta shrank by 11 entries");
    t.check(doc.read_stream(kFixed2) == before.read_stream(kFixed2),
            "delete middle: Fixed2Data changed");
    t.check(doc.read_stream(kFixed2Meta) == before.read_stream(kFixed2Meta),
            "delete middle: Fixed2Meta changed");
    t.check(doc.read_stream(kVar2) == before.read_stream(kVar2),
            "delete middle: Var2Data changed");
    std::vector<std::string> const changed = changed_streams(before, doc);
    t.check(changed.size() == 3 && contains(changed, kFixed) && contains(changed, kMeta) &&
                contains(changed, kVarMeta),
            "delete middle: changed streams are not exactly FixedData/FixedMeta/VarMeta: " +
                join_list(changed));
    check_214_untouched(t, before, doc, "w45-del-middle.mpp");
    check_table_headers(t, doc, 4, "w45-del-middle.mpp");
    emit(t, doc, "w45-del-middle.mpp",
         "synthetic-base + tombstone uid 2 (middle): ID renumber, 11 VarMeta entries removed");
    emit(t, doc, "w45-del-middle-a.mpp",
         "variant A: FixedMeta header +4 = 6, uid 2's 11 VarMeta entries removed");

    /* Variant B for the oracle: Project's own delete keeps the deleted uid's
     * VarMeta entries in the array and only decrements the declared count at
     * header +8 (w10-adddel-back: 59 entries, declared 51; -del: 59, declared
     * 43).  This is a measurement fixture, not the supported write shape: the
     * stale declared count is exactly what `validate_table` refuses on a later
     * edit.  Keep all 42 source entries and declare 42 - 11 = 31. */
    {
        std::vector<std::uint8_t> var_meta_b = before.read_stream(kVarMeta);
        t.equal(u32_at(var_meta_b, 8), 42, "variant B: the source declares 42 entries");
        put_u32_at(var_meta_b, 8, 31);
        mppwrite::CfbDocument variant_b = doc;
        variant_b.replace_stream(kVarMeta, var_meta_b);
        variant_b.save(out_path("w45-del-middle-b.mpp"));
        mppwrite::CfbDocument const reread_b =
            mppwrite::CfbDocument::from_file(out_path("w45-del-middle-b.mpp"));
        t.check(reread_b.to_bytes() == variant_b.to_bytes(),
                "variant B: the written file does not re-emit identically");
        t.check(reread_b.check().empty(),
                "variant B: container check: " + reread_b.check());
        t.check(mppwrite::check_table(reread_b).empty(),
                "variant B: check_table: " + mppwrite::check_table(reread_b));
        t.equal(fixed_meta_header_flags(reread_b), 0x06u,
                "variant B: FixedMeta header +4 is 6");
        std::vector<mppwrite::VarEntry> const entries_b =
            mppwrite::read_var_entries(reread_b.read_stream(kVarMeta));
        t.equal(entries_b.size(), 42, "variant B: all 42 VarMeta entries are kept");
        t.equal(u32_at(reread_b.read_stream(kVarMeta), 8), 31,
                "variant B: the declared count is 42 - 11");
        std::size_t uid2_entries = 0;
        for (mppwrite::VarEntry const& var_entry : entries_b) {
            uid2_entries += var_entry.mid == 2 ? 1u : 0u;
        }
        t.equal(uid2_entries, 11, "variant B: uid 2 keeps its 11 entries");
        t.check(reread_b.read_stream(kVar2) == before.read_stream(kVar2),
                "variant B: Var2Data changed");
        t.check(reread_b.read_stream(kFixed2) == before.read_stream(kFixed2),
                "variant B: Fixed2Data changed");
        std::vector<std::string> const changed_b = changed_streams(before, reread_b);
        t.check(changed_b.size() == 3 && contains(changed_b, kFixed) &&
                    contains(changed_b, kMeta) && contains(changed_b, kVarMeta),
                "variant B: changed streams: " + join_list(changed_b));
        check_214_untouched(t, before, reread_b, "w45-del-middle-b.mpp");
        emit(t, reread_b, "w45-del-middle-b.mpp",
             "variant B: +4=6, all 42 VarMeta entries kept, declared count 31");
    }

#ifdef MPPWRITE_HAVE_READER
    check_reader(t, out_path("w45-del-middle.mpp"), {1, 3}, "w45-del-middle.mpp");
    check_reader_skipped_tombstone(t, out_path("w45-del-middle.mpp"), 2,
                                   "w45-del-middle.mpp");
    check_reader(t, out_path("w45-del-middle-b.mpp"), {1, 3},
                 "w45-del-middle-b.mpp");
    check_reader_skipped_tombstone(t, out_path("w45-del-middle-b.mpp"), 2,
                                   "w45-del-middle-b.mpp");
#endif
}

