/* ---- (g) refusals ---- */
void test_refusals(TestContext& t) {
    std::string const source = join(MPPWRITE_TEST_DATA, "synthetic-base.mpp");
    mppwrite::CfbDocument const pristine = mppwrite::CfbDocument::from_file(source);

    {
        mppwrite::CfbDocument doc = pristine;
        mppwrite::NewTaskRow task;
        task.name = "W45 Duplicate";
        task.uid = 2;
        std::vector<std::uint8_t> const before = doc.to_bytes();
        expect_error(t,
                     [&] { (void)mppwrite::add_task_row(doc, task, out_path("w45-refused.mpp")); },
                     "already on", "add duplicate uid is refused");
        t.check(doc.to_bytes() == before, "add duplicate uid: document changed");
        t.check(!file_exists(out_path("w45-refused.mpp")),
                "add duplicate uid: an output file was written");
    }
    {
        mppwrite::CfbDocument doc = pristine;
        mppwrite::NewTaskRow task;
        expect_error(t,
                     [&] { (void)mppwrite::add_task_row(doc, task, out_path("w45-refused.mpp")); },
                     "name is empty", "add empty name is refused");
    }
    {
        mppwrite::CfbDocument doc = pristine;
        expect_error(t,
                     [&] {
                         (void)mppwrite::delete_task_row(doc, 0,
                                                         out_path("w45-refused.mpp"));
                     },
                     "uid 0", "delete uid 0 is refused");
    }
    {
        mppwrite::CfbDocument doc = pristine;
        expect_error(t,
                     [&] {
                         (void)mppwrite::delete_task_row(doc, 99,
                                                         out_path("w45-refused.mpp"));
                     },
                     "no task row", "delete an unknown uid is refused");
    }
    {
        mppwrite::CfbDocument doc = mppwrite::CfbDocument::from_file(
            out_path("w45-del-middle.mpp"));
        expect_error(t,
                     [&] {
                         (void)mppwrite::delete_task_row(doc, 2,
                                                         out_path("w45-refused.mpp"));
                     },
                     "already a tombstone", "delete an already-deleted uid is refused");
    }
    {
        mppwrite::CfbDocument doc = pristine;
        expect_error(t,
                     [&] {
                         (void)mppwrite::delete_task_row(doc, 2,
                                                         out_path("w45-refused.mpp"));
                     },
                     "allow_dangling",
                     "delete without opt-in is refused for its assignment rows");
        t.check(!file_exists(out_path("w45-refused.mpp")),
                "delete refusal: an output file was written");
    }
    {
        mppwrite::CfbDocument doc = pristine;
        std::vector<std::uint8_t> meta = doc.read_stream(kMeta);
        meta[12] = static_cast<std::uint8_t>(meta[12] + 1);
        doc.replace_stream(kMeta, meta);
        mppwrite::NewTaskRow task;
        task.name = "W45 Broken";
        expect_error(t,
                     [&] { (void)mppwrite::add_task_row(doc, task, out_path("w45-refused.mpp")); },
                     "size identity", "add to a broken table is refused");
        expect_error(t,
                     [&] {
                         (void)mppwrite::delete_task_row(doc, 2,
                                                         out_path("w45-refused.mpp"));
                     },
                     "size identity", "delete from a broken table is refused");
    }
    {
        mppwrite::CfbDocument doc = pristine;
        std::vector<std::uint8_t> var_meta = doc.read_stream(kVarMeta);
        var_meta[8] = static_cast<std::uint8_t>(var_meta[8] + 1); /* declared count */
        doc.replace_stream(kVarMeta, var_meta);
        mppwrite::NewTaskRow task;
        task.name = "W45 Broken";
        expect_error(t,
                     [&] { (void)mppwrite::add_task_row(doc, task, out_path("w45-refused.mpp")); },
                     "VarMeta header declares", "add with a damaged VarMeta count is refused");
    }
}

