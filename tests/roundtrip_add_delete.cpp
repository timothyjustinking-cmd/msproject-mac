class TestContext {
  public:
    void check(bool condition, std::string const& what) {
        ++checks_;
        if (!condition) {
            ++failures_;
            std::cout << "FAIL: " << what << "\n";
        }
    }
    void equal(std::size_t actual, std::size_t expected, std::string const& what) {
        check(actual == expected, what + " (actual " + std::to_string(actual) +
                                      ", expected " + std::to_string(expected) + ")");
    }
    int report() const {
        std::cout << checks_ << " checks, " << failures_ << " failures\n";
        return failures_ == 0 ? 0 : 1;
    }

  private:
    int checks_ = 0;
    int failures_ = 0;
};

std::string join(std::string const& a, std::string const& b) {
    return a + "/" + b;
}

std::string out_path(std::string const& name) {
    return join(MPPWRITE_TEST_OUT, name);
}

std::vector<std::uint8_t> read_file(std::string const& path) {
    std::ifstream input(path, std::ios::binary);
    if (!input) {
        throw std::runtime_error("cannot open " + path);
    }
    input.seekg(0, std::ios::end);
    std::streamoff const length = input.tellg();
    input.seekg(0, std::ios::beg);
    std::vector<std::uint8_t> bytes(static_cast<std::size_t>(length));
    if (!bytes.empty()) {
        input.read(reinterpret_cast<char*>(bytes.data()),
                   static_cast<std::streamsize>(bytes.size()));
    }
    return bytes;
}

void write_file(std::string const& path, std::vector<std::uint8_t> const& bytes) {
    std::ofstream output(path, std::ios::binary | std::ios::trunc);
    if (!output) {
        throw std::runtime_error("cannot create " + path);
    }
    if (!bytes.empty()) {
        output.write(reinterpret_cast<char const*>(bytes.data()),
                     static_cast<std::streamsize>(bytes.size()));
    }
    if (!output) {
        throw std::runtime_error("cannot write " + path);
    }
}

bool file_exists(std::string const& path) {
    std::error_code error;
    return std::filesystem::is_regular_file(path, error);
}

std::uint64_t fnv1a64(std::vector<std::uint8_t> const& bytes) {
    std::uint64_t hash = 1469598103934665603ULL;
    for (std::uint8_t const byte : bytes) {
        hash ^= byte;
        hash *= 1099511628211ULL;
    }
    return hash;
}

std::string hex64(std::uint64_t value) {
    static char const* digits = "0123456789abcdef";
    std::string out(16, '0');
    for (std::size_t i = 0; i < 16; ++i) {
        out[15 - i] = digits[(value >> (4 * i)) & 0xFu];
    }
    return "0x" + out;
}

std::uint16_t u16_at(std::vector<std::uint8_t> const& b, std::size_t o) {
    return static_cast<std::uint16_t>(b[o] | (b[o + 1] << 8));
}

std::uint32_t u32_at(std::vector<std::uint8_t> const& b, std::size_t o) {
    return static_cast<std::uint32_t>(b[o]) |
           (static_cast<std::uint32_t>(b[o + 1]) << 8) |
           (static_cast<std::uint32_t>(b[o + 2]) << 16) |
           (static_cast<std::uint32_t>(b[o + 3]) << 24);
}

void put_u32_at(std::vector<std::uint8_t>& b, std::size_t o, std::uint32_t v) {
    b[o] = static_cast<std::uint8_t>(v & 0xFFu);
    b[o + 1] = static_cast<std::uint8_t>((v >> 8) & 0xFFu);
    b[o + 2] = static_cast<std::uint8_t>((v >> 16) & 0xFFu);
    b[o + 3] = static_cast<std::uint8_t>((v >> 24) & 0xFFu);
}

double f64_at(std::vector<std::uint8_t> const& b, std::size_t o) {
    std::uint64_t bits = 0;
    for (std::size_t i = 0; i < 8; ++i) {
        bits |= static_cast<std::uint64_t>(b[o + i]) << (8 * i);
    }
    double value = 0.0;
    static_assert(sizeof value == sizeof bits, "IEEE-754 double expected");
    std::memcpy(&value, &bits, sizeof value);
    return value;
}

std::vector<std::string> changed_streams(mppwrite::CfbDocument const& a,
                                         mppwrite::CfbDocument const& b) {
    std::vector<std::string> out;
    for (std::string const& path : a.stream_paths()) {
        if (!b.has_stream(path)) {
            out.push_back(path + " (missing)");
        } else if (a.read_stream(path) != b.read_stream(path)) {
            out.push_back(path);
        }
    }
    return out;
}

bool contains(std::vector<std::string> const& items, std::string_view wanted) {
    return std::find(items.begin(), items.end(), wanted) != items.end();
}

std::string join_list(std::vector<std::string> const& items) {
    std::string out;
    for (std::string const& item : items) {
        if (!out.empty()) {
            out += ", ";
        }
        out += item;
    }
    return out;
}

/* The delete must touch exactly these three streams; the add must touch all six
 * table streams. */
bool only_table_streams(std::vector<std::string> const& changed) {
    for (std::string const& path : changed) {
        if (std::find(kTableStreams.begin(), kTableStreams.end(), path) ==
            kTableStreams.end()) {
            return false;
        }
    }
    return true;
}

void check_214_untouched(TestContext& t, mppwrite::CfbDocument const& before,
                         mppwrite::CfbDocument const& after, std::string const& label) {
    std::size_t compared = 0;
    for (std::string const& path : before.stream_paths()) {
        if (path.rfind("214/", 0) != 0) {
            continue;
        }
        ++compared;
        t.check(after.has_stream(path), label + ": 214/ stream vanished: " + path);
        if (after.has_stream(path)) {
            t.check(after.read_stream(path) == before.read_stream(path),
                    label + ": 214/ stream changed: " + path);
        }
    }
    t.check(compared > 0, label + ": no 214/ streams found");
}

/* Every size word and entry count the operation is supposed to maintain. */
void check_table_headers(TestContext& t, mppwrite::CfbDocument const& doc,
                         std::size_t expected_rows, std::string const& label) {
    std::vector<std::uint8_t> const fixed = doc.read_stream(kFixed);
    std::vector<std::uint8_t> const meta = doc.read_stream(kMeta);
    std::vector<std::uint8_t> const fixed2 = doc.read_stream(kFixed2);
    std::vector<std::uint8_t> const fixed2_meta = doc.read_stream(kFixed2Meta);
    std::vector<std::uint8_t> const var_meta = doc.read_stream(kVarMeta);
    std::vector<std::uint8_t> const var2 = doc.read_stream(kVar2);

    t.equal(fixed.size(), 48 + 202 * expected_rows,
            label + ": FixedData size is 48 + 202*rows");
    std::size_t const meta_entries = (meta.size() - 16) / 47;
    t.equal(meta_entries, expected_rows + 3,
            label + ": FixedMeta holds rows + 3 entries");
    t.equal(u32_at(meta, 8), meta_entries, label + ": FixedMeta +8 entry count");
    t.equal(u32_at(meta, 12), fixed.size(), label + ": FixedMeta +12 FixedData size");

    t.equal(fixed2.size(), 64 * (expected_rows + 3),
            label + ": Fixed2Data is 64 * (rows + 3)");
    std::size_t const fixed2_entries = (fixed2_meta.size() - 16) / 96;
    t.equal(fixed2_entries, expected_rows + 3,
            label + ": Fixed2Meta holds rows + 3 entries");
    t.equal(u32_at(fixed2_meta, 8), fixed2_entries,
            label + ": Fixed2Meta +8 entry count");
    t.equal(u32_at(fixed2_meta, 12), fixed2.size(),
            label + ": Fixed2Meta +12 Fixed2Data size");

    std::size_t const var_entries = (var_meta.size() - 24) / 12;
    t.equal(var_meta.size(), 24 + 12 * var_entries,
            label + ": VarMeta is 24 + 12*n");
    t.equal(u32_at(var_meta, 8), var_entries, label + ": VarMeta +8 entry count");
    t.equal(u32_at(var_meta, 20), var2.size(), label + ": VarMeta +20 Var2Data size");

    t.check(mppwrite::check_table(doc).empty(),
            label + ": check_table: " + mppwrite::check_table(doc));
    t.check(doc.check().empty(), label + ": container check: " + doc.check());
    std::vector<std::uint8_t> const bytes = doc.to_bytes();
    t.check(mppwrite::CfbDocument::from_bytes(bytes).to_bytes() == bytes,
            label + ": re-emission is not idempotent");
    t.check(bytes == read_file(out_path(label)), label + ": file on disk differs");
}

struct Fixture {
    std::string file;
    std::size_t bytes = 0;
    std::uint64_t fnv = 0;
    std::string note;
};

std::vector<Fixture>& fixtures() {
    static std::vector<Fixture> list;
    return list;
}

/* Save the fixture, prove the file holds those bytes, mirror it into the
 * coordinator's build path, and record size/FNV for the manifest. */
void emit(TestContext& t, mppwrite::CfbDocument const& doc, std::string const& name,
          std::string const& note) {
    std::string const path = out_path(name);
    doc.save(path);
    std::vector<std::uint8_t> const bytes = read_file(path);
    t.check(bytes == doc.to_bytes(), "emit " + name + ": saved bytes differ");
    Fixture fixture;
    fixture.file = name;
    fixture.bytes = bytes.size();
    fixture.fnv = fnv1a64(bytes);
    fixture.note = note;
    fixtures().push_back(fixture);

    std::error_code error;
    std::filesystem::create_directories(MPPWRITE_FIXTURE_MIRROR, error);
    write_file(join(MPPWRITE_FIXTURE_MIRROR, name), bytes);
}

void write_manifest(TestContext& t) {
    std::string json = "{\n  \"wave\": \"w45\",\n  \"generated_by\": "
                       "\"mppwrite_roundtrip_add_delete\",\n  \"fixtures\": [\n";
    for (std::size_t i = 0; i < fixtures().size(); ++i) {
        Fixture const& fixture = fixtures()[i];
        json += "    {\"file\": \"" + fixture.file + "\", \"bytes\": " +
                std::to_string(fixture.bytes) + ", \"fnv1a64\": \"" +
                hex64(fixture.fnv) + "\", \"note\": \"" + fixture.note + "\"}";
        json += (i + 1 == fixtures().size()) ? "\n" : ",\n";
    }
    json += "  ]\n}\n";
    std::vector<std::uint8_t> const bytes(json.begin(), json.end());
    write_file(out_path("w45-manifest.json"), bytes);
    std::error_code error;
    std::filesystem::create_directories(MPPWRITE_FIXTURE_MIRROR, error);
    write_file(join(MPPWRITE_FIXTURE_MIRROR, "w45-manifest.json"), bytes);
    t.check(file_exists(out_path("w45-manifest.json")),
            "manifest was not written");
}

/* FixedMeta entry (index) for a FixedData row: the entry's +4 word is the row's
 * byte offset, so row lookups go through the offset, never the array position. */
int meta_entry_for_row(std::vector<std::uint8_t> const& meta, std::size_t row) {
    std::uint32_t const wanted = static_cast<std::uint32_t>(mppwrite::task_row_offset(row));
    std::size_t const entries = (meta.size() - 16) / 47;
    for (std::size_t i = 0; i < entries; ++i) {
        if (u32_at(meta, 16 + i * 47 + 4) == wanted) {
            return static_cast<int>(i);
        }
    }
    return -1;
}

std::vector<std::uint32_t> live_uids(mppwrite::CfbDocument const& doc) {
    mppwrite::TaskTable const table = mppwrite::TaskTable::from_document(doc);
    std::vector<std::uint8_t> const meta = doc.read_stream(kMeta);
    std::vector<std::uint32_t> out;
    for (std::size_t row = 1; row < table.rows(); ++row) {
        int const entry = meta_entry_for_row(meta, row);
        if (entry >= 0 && meta[16 + static_cast<std::size_t>(entry) * 47] == 0x00) {
            out.push_back(table.uid(row));
        }
    }
    return out;
}

std::vector<std::uint32_t> live_ids(mppwrite::CfbDocument const& doc) {
    mppwrite::TaskTable const table = mppwrite::TaskTable::from_document(doc);
    std::vector<std::uint8_t> const meta = doc.read_stream(kMeta);
    std::vector<std::uint32_t> out;
    for (std::size_t row = 1; row < table.rows(); ++row) {
        int const entry = meta_entry_for_row(meta, row);
        if (entry >= 0 && meta[16 + static_cast<std::size_t>(entry) * 47] == 0x00) {
            out.push_back(table.row_id(row));
        }
    }
    return out;
}

/* FixedMeta HEADER word +4.  0x00000004 with no tombstone, 0x00000006 once the
 * table contains a deleted row (measured on Project's own add/delete files and
 * PROJECT_B).  Project ignores the per-entry tombstone without this bit. */
std::uint32_t fixed_meta_header_flags(mppwrite::CfbDocument const& doc) {
    return u32_at(doc.read_stream(kMeta), 4);
}

